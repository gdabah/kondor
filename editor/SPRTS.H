void editordrawsprt(int x, int y, int w, int h, unsigned char *sprt)
{
 for (int iy = 0; iy < h; iy++)
	for (int ix = 0; ix < w; ix++)
	 if (sprt[iy *w +ix]) ep(x +ix, y +iy, sprt[iy *w +ix]);
}
void editordrawrotsprt(int x, int y, int cx, int cy, int ang, int w, int h, unsigned char *sprt)
{
 float x_step = COS(ang),
			 y_step = SIN(ang),
			 x_step2 = COS(ang +128),
			 y_step2 = SIN(ang +128),
			 start_x = x -(cx *x_step +cy *x_step2),
			 start_y = y -(cx *y_step +cy *y_step2),
			 temp_x,
			 temp_y;
 x_step /= 2;
 y_step /= 2;
 int offset = 0;
 for (int iy = 0; iy < h; iy++)
 {
	temp_x = start_x;
	temp_y = start_y;
	for(int ix = 0; ix < w; ix++)
	{
	 for (int i = 0; i < 2; i++)
	 {
		if (sprt[offset])
		 ep(temp_x, temp_y, sprt[offset]);
		temp_x += x_step;
		temp_y += y_step;
	 }
	 offset++;
	}
	start_x += x_step2;
	start_y += y_step2;
 }
}
void editline(int x1, int y1, int x2, int y2)
{
 long int i, m, x, y;
 if (abs(x1 -x2) > abs(y1 -y2)) m = abs(x1 -x2); else m = abs(y1 -y2);
 if (m == 0)
	ep(x2, y2, gcol);
 else
 for (i = 0; i <= m; i++)
 {
	x = x1 +(x2 -x1) *i /m;
	y = y1 +(y2 -y1) *i /m;
	ep(x, y, gcol);
 }
}
void editrectangle(int x, int y, int x2, int y2)
{
 for (short i = 0; i < x2 -x; i++)
 {
	ep(x +i, y, gcol);
	ep(x +i, y2, gcol);
 }
 for (i = 0; i < y2 -y; i++)
 {
	ep(x, y +i, gcol);
	ep(x2, y +i, gcol);
 }
 ep(x2, y2, gcol);
}
